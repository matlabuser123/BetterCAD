struct Part {
    Document document{"Part"};
    features::Regenerator regenerator;
    ObjectId feature{};
    std::array<EntityId, 4> lines{};

    Part() {
        auto sketch = std::make_unique<sketch::Sketch>("Profile", Frame3D::xy());
        lines = addRectangle(*sketch, 0_mm, 0_mm, 30_mm, 20_mm);
        const ObjectId profile = require(document.addObject(std::move(sketch)));
        auto extrude = features::ExtrudeFeature::create(
            "Solid", {.profile = SketchId::fromValue(profile.value()), .depth = 10_mm});
        REQUIRE(extrude.has_value());
        feature = require(document.addObject(std::move(*extrude)));
        requireReport(regenerator, document);
    }

    [[nodiscard]] FaceName top() const {
        return FaceName{feature, FaceSelector{.role = FaceRole::EndCap}};
    }
    [[nodiscard]] FaceName bottom() const {
        return FaceName{feature, FaceSelector{.role = FaceRole::StartCap}};
    }
    [[nodiscard]] FaceName side(std::size_t which) const {
        return FaceName{feature, FaceSelector{.role = FaceRole::Side, .entity = lines[which]}};
    }
    [[nodiscard]] MeshControlDefinition definition() const {
        return MeshControlDefinition{.body = feature};
    }

    void setDepth(Length depth) {
        REQUIRE(document
                    .modifyObject<features::ExtrudeFeature>(
                        feature,
                        [depth](features::ExtrudeFeature& extrude) -> Result<bool> {
                            auto definition = extrude.definition();
                            definition.depth = depth;
                            return extrude.setDefinition(definition).has_value();
                        })
                    .has_value());
        requireReport(regenerator, document);
    }

    /// Re-profiles the extrude onto a CIRCLE, and returns the circle's entity.
    ///
    /// A topology change that keeps the feature's own ObjectId and leaves the
    /// `Side` role meaningful, while destroying the four line entities the
    /// rectangle's side faces were named by: a cylinder has one side face,
    /// generated by the circle.
    ///
    /// A CIRCLE AND NOT ANOTHER RECTANGLE, and the reason is a measurement.
    /// `EntityId` is allocated PER SKETCH, so a replacement rectangle's lines
    /// come out as the same entity numbers as the original's -- the first
    /// version of this fixture re-profiled onto a second rectangle and the
    /// control's `entity:7` resolved against the NEW sketch's seventh entity.
    /// That would have made this test assert a rebind while claiming to
    /// forbid one. See ADVERSARIAL_REVIEW.md, finding A5.
    [[nodiscard]] EntityId setProfileToCircle() {
        auto replacement = std::make_unique<sketch::Sketch>("Round", Frame3D::xy());
        const EntityId circle =
            require(replacement->addCircle(Point2D{10_mm, 10_mm}, 8_mm));
        const ObjectId profile = require(document.addObject(std::move(replacement)));
        REQUIRE(document
                    .modifyObject<features::ExtrudeFeature>(
                        feature,
                        [profile](features::ExtrudeFeature& extrude) -> Result<bool> {
                            auto definition = extrude.definition();
                            definition.profile = SketchId::fromValue(profile.value());
                            return extrude.setDefinition(definition).has_value();
                        })
                    .has_value());
        requireReport(regenerator, document);
        return circle;
    }
};

template <typename CommandType, typename... Args>
CommandType* run(CommandHistory& history, Document& document, Args&&... args) {
    auto command = std::make_unique<CommandType>(std::forward<Args>(args)...);
    CommandType* raw = command.get();
    const Result<void> result = history.execute(document, std::move(command));
    INFO((result ? std::string{} : result.error().message));
    REQUIRE(result.has_value());
    return raw;
}

template <typename CommandType, typename... Args>
[[nodiscard]] Error runExpectingFailure(CommandHistory& history, Document& document,
                                        Args&&... args) {
    auto command = std::make_unique<CommandType>(std::forward<Args>(args)...);
    const Result<void> result = history.execute(document, std::move(command));
    REQUIRE_FALSE(result.has_value());
    return result.error();
}

void requireUndo(CommandHistory& history, Document& document) {
    const Result<void> result = history.undo(document);
    INFO((result ? std::string{} : result.error().message));
    REQUIRE(result.has_value());
}

void requireRedo(CommandHistory& history, Document& document) {
    const Result<void> result = history.redo(document);
    INFO((result ? std::string{} : result.error().message));
    REQUIRE(result.has_value());
}

[[nodiscard]] const MeshControlDefinition& definitionOf(const Document& document,
                                                        MeshControlId control) {
    const MeshControl* found = meshing::findMeshControl(document, control);
    REQUIRE(found != nullptr);
    return found->definition();
}

/// Every field of a face reference, because a fingerprint that skipped one
/// could not detect an undo that lost it.
///
/// `FaceSelector`'s entity, path edge, sketch and chamfer-edge are all
/// OPTIONAL -- an end cap names no entity, a side face does -- so an absent
/// one is rendered as a distinct token rather than unwrapped. Unwrapping it
/// was the first version of this helper, and it threw on the first end-cap
/// control it saw.
[[nodiscard]] std::string describe(const FaceName& name) {
    const auto id = [](const auto& optional) {
        return optional.has_value() ? std::format("{}", optional->value()) : std::string{"-"};
    };
    std::string text = std::format("{},{},{},{},{},{}", name.feature.value(),
                                   static_cast<int>(name.face.role), id(name.face.entity),
                                   id(name.face.along), id(name.face.alongSketch),
                                   id(name.face.edge));
    for (const FaceCopy& copy : name.face.copies) {
        text += std::format(",copy({},{})", copy.feature.value(), copy.instance);
    }
    return text;
}

/// A deterministic rendering of the CANONICAL MESHING INTENT, and of nothing
/// else.
///
/// It reads only what a command may carry: the body, the discretisation and
/// sizing, the threshold policy and the boundary intent. There is deliberately
/// no mesh in it -- no node count, no element count, no quality figure -- so a
/// fingerprint that matched after an undo could not be matching because a
/// cached mesh happened to be the same.
///
/// Enumerated through the control's ordered accessors, because the stored
/// order of local controls carries no meaning (P16-SIZE-001) and a fingerprint
/// that depended on it would change when nothing semantic had.
[[nodiscard]] std::string fingerprint(const MeshControl& control) {
    const MeshControlDefinition& definition = control.definition();
    std::string text = std::format("body={}", definition.body.value());
    text += std::format("|global={}",
                        definition.mesh.sizing.globalTargetSize.has_value()
                            ? std::format("{:.12g}", definition.mesh.sizing.globalTargetSize->si())
                            : std::string{"default"});
    text += std::format("|deflection={:.12g}/{:.12g}",
                        definition.mesh.surface.linearDeflection.si(),
                        definition.mesh.surface.angularDeflection.si());
    for (const LocalMeshSizing& local : control.orderedLocalSizing()) {
        text += std::format("|local[{}]={:.12g}", describe(local.face), local.targetSize.si());
    }
    for (const NamedBoundarySet& set : control.orderedBoundarySets()) {
        text += std::format("|set[{}:{}]=", set.id.value(), set.name);
        for (const FaceName& face : set.faces) {
            text += std::format("({})", describe(face));
        }
    }
    for (const auto& [metric, threshold] : definition.quality.limits) {
        text += std::format("|limit[{}]={:.12g}/{:.12g}", static_cast<int>(metric),
                            threshold.warning.value_or(0.0), threshold.failure.value_or(0.0));
    }
    return text;
}

[[nodiscard]] std::string fingerprintOf(const Document& document, MeshControlId control) {
    const MeshControl* found = meshing::findMeshControl(document, control);
    REQUIRE(found != nullptr);
    return fingerprint(*found);
}

/// A cylinder, r 6 x h 20 mm.
///
/// THE FIXTURE THAT CAN SHOW SIZING AT ALL, and P16-SIZE-001 established it
/// for the same reason: a volume element cannot be smaller than the boundary
/// triangles it must conform to, and OCCT triangulates a PLANAR face with two
/// triangles whatever the deflection. The block above saturates at 24
/// tetrahedra -- 10 mm, 3 mm and 1.5 mm all give 24 -- so it cannot
/// demonstrate a mesh growing while a history step does not. A curved wall
/// subdivides with the deflection, so a cylinder can.
struct Tube {
    Document document{"Tube"};
    features::Regenerator regenerator;
    ObjectId feature{};

    Tube() {
        auto sketch = std::make_unique<sketch::Sketch>("Profile", Frame3D::xy());
        REQUIRE(sketch->addCircle(Point2D{0_mm, 0_mm}, 6_mm).has_value());
        const ObjectId profile = require(document.addObject(std::move(sketch)));
        auto extrude = features::ExtrudeFeature::create(
            "Solid", {.profile = SketchId::fromValue(profile.value()), .depth = 20_mm});
        REQUIRE(extrude.has_value());
        feature = require(document.addObject(std::move(*extrude)));
        requireReport(regenerator, document);
    }

    [[nodiscard]] FaceName top() const {
        return FaceName{feature, FaceSelector{.role = FaceRole::EndCap}};
    }
    [[nodiscard]] FaceName bottom() const {
        return FaceName{feature, FaceSelector{.role = FaceRole::StartCap}};
    }
    [[nodiscard]] MeshControlDefinition definition() const {
        return MeshControlDefinition{.body = feature};
    }
};

/// A control with a global size, so a sequence has something to restore.
template <typename Fixture>
[[nodiscard]] MeshControlId makeControl(Fixture& part, CommandHistory& history) {
    MeshControlDefinition definition = part.definition();
    definition.mesh.sizing.globalTargetSize = 10_mm;
    CreateMeshControlCommand* create =
        run<CreateMeshControlCommand>(history, part.document, "Mesh", definition);
    const MeshControlId control = create->meshControlId();
    REQUIRE(control.isValid());
    return control;
}

