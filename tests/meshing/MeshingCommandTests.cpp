// P16-CMD-001: meshing commands, undo and redo.
//
// WHAT "EXACT" MEANS HERE, and it is the reason for the fingerprint below.
// Undo is not "the numbers look the same": it is that the canonical meshing
// intent after an undo equals the intent before the command, field for field,
// including the body it names, every local control's face reference and size,
// every boundary set's identity, name and selection, and the threshold policy.
// A fingerprint makes that one comparison instead of twenty, and makes a
// multi-step sequence checkable as a sequence.
//
// AND WHAT IS NEVER IN THE HISTORY: no nodes, no elements, no connectivity, no
// facet identities, no quality report, no mapping, no backend handle. The mesh
// an undo "restores" is not restored at all -- it is recomputed from the intent
// on the next request, which is what ADR-030 requires and what makes a history
// step cost a few bytes rather than a few megabytes.

