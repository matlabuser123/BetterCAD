// Regenerate after load
// ---------------------------------------------------------------------------
//
// The milestone's hard gate. A loaded document carries intent and NO mesh; the
// mesh comes from the loaded geometry plus the loaded intent, on request. What
// these tests compare is the mesh SEMANTICS, never a mesh identity: NodeId and
// ElementId belong to one generation and persistence promises nothing about
