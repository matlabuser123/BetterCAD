// P16-PERSIST-001: persisting canonical meshing intent.
//
// THE RULE THESE TESTS EXIST FOR:
//
//     save  ->  meshing intent
//     load  ->  regenerate from current geometry + intent
//
// NOT: save 100,000 tetrahedra and trust them afterwards. So the comparisons
// here are of CANONICAL INTENT, by the same fingerprint P16-CMD-001 uses --
// which reads the body, the deflections, the ordered local controls, the
// ordered boundary sets and the threshold policy, and reads nothing generated.
// A fingerprint that matched because a cached mesh happened to match would be
// no evidence at all.

