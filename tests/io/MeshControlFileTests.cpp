/// The fixture the brief calls for: asymmetric geometry, a global size, two
/// local controls, one resolved reference, one that cannot resolve, and two
/// named boundary sets.
struct Part {
    Document document{"Part"};
    features::Regenerator regenerator;
    ObjectId feature{};
    std::array<EntityId, 4> lines{};

    Part() {
        auto sketch = std::make_unique<sketch::Sketch>("Profile", Frame3D::xy());
        // 30 x 20, not square: an asymmetric body cannot have two faces
        // accidentally interchangeable.
        lines = addRectangle(*sketch, 0_mm, 0_mm, 30_mm, 20_mm);
        const ObjectId profile = require(document.addObject(std::move(sketch)));
        auto extrude = features::ExtrudeFeature::create(
            "Solid", {.profile = SketchId::fromValue(profile.value()), .depth = 10_mm});
        REQUIRE(extrude.has_value());
        feature = require(document.addObject(std::move(*extrude)));
        requireReport(regenerator, document);
    }

    [[nodiscard]] FaceName top() const {
        return FaceName{feature, FaceSelector{.role = FaceRole::EndCap}};
    }
    [[nodiscard]] FaceName bottom() const {
        return FaceName{feature, FaceSelector{.role = FaceRole::StartCap}};
    }
    [[nodiscard]] FaceName side(std::size_t which) const {
        return FaceName{feature, FaceSelector{.role = FaceRole::Side, .entity = lines[which]}};
    }
    /// A reference that is well formed and names an entity no face is
    /// generated by: unresolved, not malformed. The distinction is the whole
    /// of P16-PERSIST's §77.
    [[nodiscard]] FaceName unresolvable() const {
        return FaceName{feature, FaceSelector{.role = FaceRole::Side,
                                              .entity = EntityId::fromValue(9999U)}};
    }
};

/// A cylinder, r 6 x h 20 mm: the fixture that can show a mesh growing.
struct Tube {
    Document document{"Tube"};
    features::Regenerator regenerator;
    ObjectId feature{};

    Tube() {
        auto sketch = std::make_unique<sketch::Sketch>("Profile", Frame3D::xy());
        REQUIRE(sketch->addCircle(Point2D{0_mm, 0_mm}, 6_mm).has_value());
        const ObjectId profile = require(document.addObject(std::move(sketch)));
        auto extrude = features::ExtrudeFeature::create(
            "Solid", {.profile = SketchId::fromValue(profile.value()), .depth = 20_mm});
        REQUIRE(extrude.has_value());
        feature = require(document.addObject(std::move(*extrude)));
        requireReport(regenerator, document);
    }
};

[[nodiscard]] std::string describe(const FaceName& name) {
    const auto id = [](const auto& optional) {
        return optional.has_value() ? std::format("{}", optional->value()) : std::string{"-"};
    };
    std::string text = std::format("{},{},{},{},{},{}", name.feature.value(),
                                   static_cast<int>(name.face.role), id(name.face.entity),
                                   id(name.face.along), id(name.face.alongSketch),
                                   id(name.face.edge));
    for (const FaceCopy& copy : name.face.copies) {
        text += std::format(",copy({},{})", copy.feature.value(), copy.instance);
    }
    return text;
}

/// Canonical meshing intent, and nothing else. The same shape P16-CMD-001's
/// command tests use, so the two milestones compare the same thing.
[[nodiscard]] std::string fingerprint(const MeshControl& control) {
    const MeshControlDefinition& definition = control.definition();
    std::string text = std::format("body={}", definition.body.value());
    text += std::format("|global={}",
                        definition.mesh.sizing.globalTargetSize.has_value()
                            ? std::format("{:.12g}", definition.mesh.sizing.globalTargetSize->si())
                            : std::string{"default"});
    text += std::format("|deflection={:.12g}/{:.12g}",
                        definition.mesh.surface.linearDeflection.si(),
                        definition.mesh.surface.angularDeflection.si());
    for (const LocalMeshSizing& local : control.orderedLocalSizing()) {
        text += std::format("|local[{}]={:.12g}", describe(local.face), local.targetSize.si());
    }
    for (const NamedBoundarySet& set : control.orderedBoundarySets()) {
        text += std::format("|set[{}:{}]=", set.id.value(), set.name);
        for (const FaceName& face : set.faces) {
            text += std::format("({})", describe(face));
        }
    }
    for (const auto& [metric, threshold] : definition.quality.limits) {
        text += std::format("|limit[{}]={:.12g}/{:.12g}", static_cast<int>(metric),
                            threshold.warning.value_or(0.0), threshold.failure.value_or(0.0));
    }
    return text;
}

[[nodiscard]] const MeshControl& onlyControl(const Document& document) {
    const std::vector<MeshControlId> controls = meshing::meshControls(document);
    REQUIRE(controls.size() == 1U);
    const MeshControl* found = meshing::findMeshControl(document, controls.front());
    REQUIRE(found != nullptr);
    return *found;
}

/// The full fixture's definition, built once so every test compares the same
/// intent.
[[nodiscard]] MeshControlDefinition fullDefinition(const Part& part) {
    MeshControlDefinition definition;
    definition.body = part.feature;
    definition.mesh.surface.linearDeflection = Length::fromSi(5e-5);
    definition.mesh.surface.angularDeflection = Angle::fromSi(0.25);
    definition.mesh.sizing.globalTargetSize = 8_mm;
    definition.mesh.sizing.local.push_back(
        LocalMeshSizing{.face = part.side(2), .targetSize = 2_mm});
    definition.mesh.sizing.local.push_back(LocalMeshSizing{.face = part.top(), .targetSize = 1_mm});
    // The one that cannot resolve, carried as intent.
    definition.mesh.sizing.local.push_back(
        LocalMeshSizing{.face = part.unresolvable(), .targetSize = 3_mm});
    definition.quality.limits.emplace(
        QualityMetric::TetMinDihedralAngle,
        QualityThreshold{.warning = 0.3, .failure = 0.1});
    definition.boundarySets.push_back(NamedBoundarySet{
        .id = BoundarySetId::fromValue(4U), .name = "fixed_end", .faces = {part.bottom()}});
    definition.boundarySets.push_back(
        NamedBoundarySet{.id = BoundarySetId::fromValue(2U),
                         .name = "loaded",
                         .faces = {part.side(0), part.side(1)}});
    return definition;
}

[[nodiscard]] MeshControlId addControl(Document& document, std::string name,
                                       MeshControlDefinition definition) {
    auto control = MeshControl::create(std::move(name), std::move(definition));
    INFO((control ? std::string{} : control.error().message));
    REQUIRE(control.has_value());
    const ObjectId id = require(document.addObject(std::move(*control)));
    return MeshControlId::fromValue(id.value());
}

/// Round trips a document through the real file path, not through a string.
[[nodiscard]] Document roundTrip(const Document& document, const std::filesystem::path& file) {
    const Result<void> saved = io::saveDocument(document, file);
    INFO((saved ? std::string{} : saved.error().message));
    REQUIRE(saved.has_value());
    Result<Document> loaded = io::loadDocument(file);
    INFO((loaded ? std::string{} : loaded.error().message));
    REQUIRE(loaded.has_value());
    return std::move(*loaded);
}

/// Replaces the mesh-control object's `data` in a saved file, so a malformed
/// field can be tested without a hand-written whole document.
[[nodiscard]] std::string withControlData(const std::string& json, std::string_view replacement) {
    const std::size_t typeAt = json.find("\"type\": \"mesh-control\"");
    REQUIRE(typeAt != std::string::npos);
    const std::size_t dataAt = json.find("\"data\":", typeAt);
    REQUIRE(dataAt != std::string::npos);
    const std::size_t open = json.find('{', dataAt);
    REQUIRE(open != std::string::npos);
    // Walk to the matching brace, so nested objects are handled.
    std::size_t depth = 0;
    std::size_t close = open;
    for (; close < json.size(); ++close) {
        if (json[close] == '{') {
            ++depth;
        } else if (json[close] == '}') {
            --depth;
            if (depth == 0) {
                break;
            }
        }
    }
    REQUIRE(close < json.size());
    return json.substr(0, open) + std::string{replacement} + json.substr(close + 1);
}

[[nodiscard]] Error loadFailure(std::string_view json) {
    Result<Document> loaded = io::documentFromJson(json);
    REQUIRE_FALSE(loaded.has_value());
    return loaded.error();
}

